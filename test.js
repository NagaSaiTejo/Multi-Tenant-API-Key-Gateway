const http = require('http');

const data = JSON.stringify({ rateLimitPerMinute: 5 });

const options = {
  hostname: 'localhost',
  port: 3000,
  path: '/api/tenants/1/keys',
  method: 'POST',
  headers: {
    'Content-Type': 'application/json',
    'Content-Length': data.length
  }
};

const req = http.request(options, (res) => {
  let responseData = '';
  res.on('data', (chunk) => {
    responseData += chunk;
  });
  res.on('end', () => {
    console.log(responseData);
  });
});

req.on('error', (e) => {
  console.error(`Problem with request: ${e.message}`);
});

req.write(data);
req.end();
